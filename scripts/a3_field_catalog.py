"""Write docs/field_reliability.md from the field catalog (src/credit_risk/field_catalog.py)."""
import pandas as pd

from credit_risk.field_catalog import catalog_frame

df = catalog_frame()
ROLE = {"input": "model input", "platform_score": "platform score (benchmark only)", "restricted": "restricted (fairness review)",
        "time_key": "time key", "id": "identifier", "target": "target", "excluded": "excluded"}


def table(rows):
    lines = ["| Field | Source | Reliability | Role | Reason and evidence |", "|---|---|---|---|---|"]
    for r in rows.itertuples():
        lines.append(f"| `{r.field}` | {r.source} | {r.reliability} | {ROLE[r.role]} | {r.reason} |")
    return "\n".join(lines)


avail = df[df.known_at_application]
late = df[~df.known_at_application]
counts = avail[avail.reliability != "n/a"].reliability.value_counts()
text = f"""# Field reliability and what was known at application time

Generated by `scripts/a3_field_catalog.py` from `src/credit_risk/field_catalog.py`.

## How fields were rated
- **high**: recorded by the platform or the credit bureau, internally consistent, and either no errors or
  a small share (about 1%) that were found and repaired.
- **medium**: reported by the borrower but consistent in the tests, or a system field with errors that
  could not be fully repaired, or with large structural missingness.
- **low**: free text, or a field whose content is duplicated, unreliable or a leak.

Evidence: `issue_log.md`, `reports/a3_reliability_evidence/` (income by verification status, consistency with
income, missingness), `reports/a3_platform_score_check/`.

Of the {len(avail[avail.reliability != 'n/a'])} rated fields known at application time:
{counts.get('high', 0)} high, {counts.get('medium', 0)} medium, {counts.get('low', 0)} low.

## Known when the applicant applies ({len(avail)} fields)
{table(avail)}

## Not known at application time ({len(late)} fields), excluded from every model input
A field is excluded when it is recorded after the loan is issued, or when it is a copy of such a field.
The servicing file is a March 2019 snapshot of how each loan went, so each of its columns reveals the
outcome. It is used to audit the label and never reaches the model.

{table(late)}

## Findings that drive the ratings
- **Income is usable but not verified for everyone.** Median stated income is $58k for unverified and $66-67k
  for verified applicants. Income relates to total credit limits equally well in all groups (rank correlation
  0.55 to 0.57), installments never exceed 40% of income, and `dti` rises with revolving balance relative to
  income (0.36 to 0.43). The 3% of incomes typed in thousands occur equally in every group.
- **Missing values are structural, not random, and not clearly linked to default.** Each can be predicted from other
  fields (AUC 0.80 to 0.87), and none differs significantly in default rate (all p-values above 0.09).
  `mths_since_last_delinq` is missing when there is no delinquency on record (99.7% of the missing have none in
  two years). `emp_title` and `emp_length` are missing together and more often among verified applicants.
  `bc_util` is missing for borrowers with few open accounts.
- **Verification is not a safety signal.** Verified loans default more (19% vs 13%), probably because the platform
  chooses whom to verify.
"""
open("docs/field_reliability.md", "w").write(text)
print(df.groupby(["known_at_application", "reliability"]).size())
